using System;
using System.Collections.Generic;
using System.IO;
using System.Linq;
using System.Threading.Tasks;
using Aspenlaub.Net.GitHub.CSharp.Pegh.Interfaces;
using Aspenlaub.Net.GitHub.CSharp.Skladasu.Entities;
using Aspenlaub.Net.GitHub.CSharp.Skladasu.Extensions;
using Autofac;
using Cake.Frosting;

namespace Aspenlaub.Net.GitHub.CSharp.Shatilaya.Tasks;

[TaskName("EnsureShatilayaCmd")]
[TaskDescription("Create or update shatilaya.cmd")]
public class EnsureShatilayaCmdTask : AsyncFrostingTask<ShatilayaContext> {
    public override async Task RunAsync(ShatilayaContext context) {
        var errorsAndInfos = new ErrorsAndInfos();
        IFolder shatilayaReleaseFolder = await context.Container.Resolve<IFolderResolver>().ResolveAsync("$(Shatilaya)", errorsAndInfos);
        if (errorsAndInfos.AnyErrors()) {
            throw new Exception(errorsAndInfos.ErrorsToString());
        }
        IFolder shatilayaWorkerFolder = await context.Container.Resolve<IFolderResolver>().ResolveAsync("$(ShatilayaWorker)", errorsAndInfos);
        if (errorsAndInfos.AnyErrors()) {
            throw new Exception(errorsAndInfos.ErrorsToString());
        }
        var executableFullNames = Directory.GetFiles(shatilayaReleaseFolder.FullName, "*Shatilaya*.exe").ToList();
        if (executableFullNames.Count != 1) {
            throw new Exception("Shatilaya executable not found or not unique");
        }

        string executableShortName = executableFullNames[0].Substring(executableFullNames[0].LastIndexOf("\\", StringComparison.Ordinal) + 1);
        List<string> lines = context.SolutionId == "Shatilaya" ? [
            $"set \"SOURCE={shatilayaReleaseFolder.FullName}\"",
            $"set \"DEST={shatilayaWorkerFolder.FullName}\"",
            "robocopy \"%SOURCE%\" \"%DEST%\" /E /R:3 /W:5",
            "cd \"%DEST%\"",
            $"{executableShortName} --repository {context.RepositoryFolder.FullName} %*",
            "pause"
        ] : [
            $"cd {shatilayaReleaseFolder.FullName}",
            $"{executableShortName} --repository {context.RepositoryFolder.FullName} %*",
            "pause"
        ];
        string contents = string.Join("\r\n", lines);
        string fileName = context.RepositoryFolder.FullName + @"\\shatilaya.cmd";
        if (!File.Exists(fileName) || contents != await File.ReadAllTextAsync(fileName)) {
            await File.WriteAllTextAsync(fileName, contents);
        }

        fileName = context.RepositoryFolder.FullName + @"\\.gitignore";
        if (!File.Exists(fileName)) {
            throw new FileNotFoundException(fileName);
        }

        lines = [.. await File.ReadAllLinesAsync(fileName)];
        if (lines.Any(x => x.Contains("shatilaya.cmd"))) {
            return;
        }

        if (!string.IsNullOrEmpty(lines[lines.Count - 1])) {
            lines.Add("");
        }
        lines.Add("# Generated by the little things");
        lines.Add("shatilaya.cmd");
        lines.Add("");
        await File.WriteAllLinesAsync(fileName, lines);
    }
}
